/**
 * @param {MixamoMotion} motion - Catalog row.
 * @returns {string} File stem used for FBX / GLB.
 */
export function motionSlug(motion) {
    const label = motion.name.toLowerCase() === motion.desc.toLowerCase()
        ? motion.name
        : `${motion.name} ${motion.desc}`;
    const s = label.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
    return `${motion.id}-${s}`;
}

/**
 * @param {MixamoMotion} motion - Catalog row.
 * @returns {string} Dropdown / list label.
 */
export function motionLabel(motion) {
    return motion.name.toLowerCase() === motion.desc.toLowerCase()
        ? motion.name
        : `${motion.name} — ${motion.desc}`;
}

/**
 * @param {MixamoMotion} motion - Catalog row.
 * @returns {string} Public GLB URL.
 */
export function motionGlbUrl(motion) {
    return `/assets/charcter/motion/${motionSlug(motion)}.glb`;
}

/**
 * @param {string} id - Mixamo model-id.
 * @returns {MixamoMotion|undefined} Catalog row.
 */
export function motionById(id) {
    return MIXAMO_MOTIONS.find((motion) => motion.id === id);
}

/**
 * @param {string} id - Mixamo model-id present in {@link MIXAMO_MOTIONS}.
 * @returns {string} Public GLB URL for that clip.
 */
function clipUrl(id) {
    const motion = motionById(id);
    if (!motion) {
        throw new Error(`mixamo-catalog: unknown motion id ${id}`);
    }
    return motionGlbUrl(motion);
}

