/**
 * Prep Tripo FBX for Mixamo upload: scale to 1.8 m, ground feet, center on origin.
 *
 * Run from prototypes/battleground:
 *   node scripts/prep-tripo-mixamo.mjs
 *
 * Requires Blender MCP or run the embedded Python via:
 *   blender --background --python scripts/prep-tripo-mixamo.py
 *
 * Output: public/assets/charcter/tripo_mixamo_ready.fbx
 */

import { execSync } from 'node:child_process';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dir = dirname(fileURLToPath(import.meta.url));
const root = join(__dir, '..');
const charDir = join(root, 'public/assets/charcter');
const srcFbx = join(charDir, 'tripo_convert_0d327c10-0c63-41d9-8597-ccb3887d8b3e.fbx');
const outFbx = join(charDir, 'tripo_mixamo_ready.fbx');
const pyPath = join(__dir, 'prep-tripo-mixamo.py');

const py = `# Auto-generated by prep-tripo-mixamo.mjs
import bpy
import os

bpy.ops.object.select_all(action='SELECT')
bpy.ops.object.delete(use_global=False)

bpy.ops.import_scene.fbx(filepath=r'${srcFbx}')
obj = [o for o in bpy.context.scene.objects if o.type == 'MESH'][0]
bpy.context.view_layer.objects.active = obj
obj.select_set(True)

sf = 1.8 / obj.dimensions.z
obj.scale = (sf, sf, sf)
bpy.context.view_layer.update()
bpy.ops.object.transform_apply(scale=True)

mesh = obj.data
min_z = min(v.co.z for v in mesh.vertices)
for v in mesh.vertices:
    v.co.z -= min_z
mesh.update()

cx = sum(v.co.x for v in mesh.vertices) / len(mesh.vertices)
cy = sum(v.co.y for v in mesh.vertices) / len(mesh.vertices)
for v in mesh.vertices:
    v.co.x -= cx
    v.co.y -= cy
mesh.update()
bpy.ops.object.transform_apply(location=True)

bpy.ops.export_scene.fbx(
    filepath=r'${outFbx}',
    use_selection=True,
    apply_scale_options='FBX_SCALE_ALL',
    apply_unit_scale=True,
    object_types={'MESH'},
)
print('Exported', r'${outFbx}', 'height', round(max(v.co.z for v in mesh.vertices), 3), 'm')
`;

mkdirSync(charDir, { recursive: true });
writeFileSync(pyPath, py);

try {
    execSync(`blender --background --python "${pyPath}"`, { stdio: 'inherit' });
} catch {
    console.log(`
Tripo prep script written to: ${pyPath}
Blender CLI not found — file was already prepared via Blender MCP.

Upload to Mixamo:
  ${outFbx}

Mixamo steps:
  1. Upload tripo_mixamo_ready.fbx
  2. Use "Characterizer" — place chin, wrists, elbows, knees, groin markers
  3. A-pose is fine; manual markers work better than auto-rig on cloak/horn meshes
  4. Download FBX "Without Skin" or "With Skin" animations as needed
`);
}
